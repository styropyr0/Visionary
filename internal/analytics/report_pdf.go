// Reports as PDF: the weekly digest (attached to digest emails) and the
// security report. Both are laid out from a reportDoc, which holds the same
// summary, stat tiles and sections as the digest email, so the email and the
// PDF never disagree. A4, Helvetica, one accent color; tables wrap long
// values instead of cutting them, and repeat their header on a new page.

type reportDoc struct {
	App       string
	Kind      string // the line above the title: "Weekly digest", "Security report"
	Title     string
	Period    string
	TimeZone  string
	Generated time.Time
	Verdict   *reportVerdict
	Summary   []string // the first line is the headline
	Stats     []emailStat
	Chart     *reportChart
	Sections  []emailSection
	Footnote  string
}

// reportVerdict is the box under the title. Tone is good, bad or warn.
type reportVerdict struct {
	Tone, Title, Text string
}

// reportChart is a bar per label; Marks (optional, same scale) are drawn
// over the bars from the bottom, like 5xx inside a day's requests.
type reportChart struct {
	Title, Note        string
	Labels             []string
	Values, Marks      []float64
	ValueName, MarkName string
}

type rgb struct{ r, g, b int }

var (
	pdfInk    = rgb{29, 35, 48}
	pdfMuted  = rgb{107, 114, 128}
	pdfFaint  = rgb{154, 161, 173}
	pdfLine   = rgb{227, 230, 235}
	pdfTile   = rgb{245, 246, 248}
	pdfHead   = rgb{238, 241, 245}
	pdfZebra  = rgb{250, 251, 252}
	pdfAccent = rgb{31, 95, 174}  // the logo's eye
	pdfSun    = rgb{217, 119, 11} // the logo's sun
	pdfGood   = rgb{12, 122, 44}
	pdfBad    = rgb{194, 47, 47}
	pdfWarn   = rgb{138, 90, 0}
)

const (
	pdfMargin = 18.0
	pdfTop    = 16.0
	pdfBottom = 18.0
)

//go:embed assets/logo.svg
var logoSVG string

type reportPDF struct {
	f     *fpdf.Fpdf
	tr    func(string) string
	doc   reportDoc
	width float64 // usable width
}

func renderReportPDF(doc reportDoc) ([]byte, error) {
	f := fpdf.New("P", "mm", "A4", "")
	f.SetMargins(pdfMargin, pdfTop, pdfMargin)
	f.SetAutoPageBreak(false, pdfBottom)
	f.SetTitle(doc.Kind+" · "+doc.App, true)
	f.SetAuthor("Visionary", true)
	f.SetCreator("Visionary", true)
	f.SetProducer("Visionary", true)
	f.SetCreationDate(doc.Generated)
	f.AliasNbPages("{nb}")
	w, _ := f.GetPageSize()
	r := &reportPDF{f: f, tr: f.UnicodeTranslatorFromDescriptor(""), doc: doc, width: w - 2*pdfMargin}
	f.SetHeaderFunc(r.runningHeader)
	f.SetFooterFunc(r.footer)
	f.AddPage()

	r.cover()
	if doc.Verdict != nil {
		r.verdict(*doc.Verdict)
	}
	if len(doc.Summary) > 0 {
		r.summary(doc.Summary)
	}
	if len(doc.Stats) > 0 {
		r.stats(doc.Stats)
	}
	if doc.Chart != nil && len(doc.Chart.Values) > 0 {
		r.chart(*doc.Chart)
	}
	for _, s := range doc.Sections {
		r.section(s)
	}
	if doc.Footnote != "" {
		r.footnote(doc.Footnote)
	}
	var b bytes.Buffer
	if err := f.Output(&b); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// ---------- page furniture ----------

func (r *reportPDF) color(c rgb)     { r.f.SetTextColor(c.r, c.g, c.b) }
func (r *reportPDF) fill(c rgb)      { r.f.SetFillColor(c.r, c.g, c.b) }
func (r *reportPDF) draw(c rgb)      { r.f.SetDrawColor(c.r, c.g, c.b) }
func (r *reportPDF) font(style string, size float64) { r.f.SetFont("Helvetica", style, size) }

// pdfReplacer maps characters the core fonts lack (they cover Windows-1252)
// to near equivalents before translating.
var pdfReplacer = strings.NewReplacer("→", "›", "←", "‹", "≥", ">=", "≤", "<=", "✓", "OK")

func (r *reportPDF) text(s string) string { return r.tr(pdfReplacer.Replace(s)) }

func (r *reportPDF) pageBottom() float64 {
	_, h := r.f.GetPageSize()
	return h - pdfBottom
}

// need starts a new page unless h millimetres still fit.
func (r *reportPDF) need(h float64) {
	if r.f.GetY()+h > r.pageBottom() {
		r.f.AddPage()
	}
}

// runningHeader is on every page but the first, which has the cover.
func (r *reportPDF) runningHeader() {
	if r.f.PageNo() == 1 {
		return
	}
	y := 9.0
	r.logo(pdfMargin, y-1, 5)
	r.font("B", 8)
	r.color(pdfInk)
	r.f.SetXY(pdfMargin+7, y)
	r.f.CellFormat(80, 4, r.text("Visionary · "+r.doc.Kind), "", 0, "L", false, 0, "")
	r.font("", 8)
	r.color(pdfMuted)
	r.f.SetXY(pdfMargin, y)
	r.f.CellFormat(r.width, 4, r.text(r.doc.Period), "", 0, "R", false, 0, "")
	r.draw(pdfLine)
	r.f.SetLineWidth(0.2)
	r.f.Line(pdfMargin, y+6, pdfMargin+r.width, y+6)
	r.f.SetY(pdfTop + 4)
}

func (r *reportPDF) footer() {
	_, h := r.f.GetPageSize()
	y := h - 12
	r.draw(pdfLine)
	r.f.SetLineWidth(0.2)
	r.f.Line(pdfMargin, y-2, pdfMargin+r.width, y-2)
	r.font("", 7.5)
	r.color(pdfFaint)
	left := "Generated by Visionary"
	if r.doc.App != "" {
		left += " for " + r.doc.App
	}
	left += " · " + r.doc.Generated.Format("2 Jan 2006, 15:04 MST")
	r.f.SetXY(pdfMargin, y)
	r.f.CellFormat(r.width, 4, r.text(left), "", 0, "L", false, 0, "")
	r.f.SetXY(pdfMargin, y)
	r.f.CellFormat(r.width, 4, fmt.Sprintf("Page %d of {nb}", r.f.PageNo()), "", 0, "R", false, 0, "")
}

func (r *reportPDF) cover() {
	f := r.f
	y := pdfTop
	r.logo(pdfMargin, y, 9)
	r.font("B", 12)
	r.color(pdfInk)
	f.SetXY(pdfMargin+11, y+2)
	f.CellFormat(60, 5, "Visionary", "", 0, "L", false, 0, "")
	if r.doc.App != "" {
		r.font("", 9)
		r.color(pdfMuted)
		f.SetXY(pdfMargin, y+2.4)
		f.CellFormat(r.width, 5, r.text(r.doc.App), "", 0, "R", false, 0, "")
	}
	y += 20
	r.font("B", 8.5)
	r.color(pdfAccent)
	f.SetXY(pdfMargin, y)
	f.CellFormat(r.width, 4, r.text(strings.ToUpper(r.doc.Kind)), "", 0, "L", false, 0, "")
	y += 6
	r.font("B", 22)
	r.color(pdfInk)
	f.SetXY(pdfMargin, y)
	f.MultiCell(r.width, 9, r.text(r.doc.Title), "", "L", false)
	y = f.GetY() + 3

	// Period, time zone and when, as small labelled columns.
	meta := [][2]string{{"Period", r.doc.Period}}
	if r.doc.TimeZone != "" {
		meta = append(meta, [2]string{"Time zone", r.doc.TimeZone})
	}
	meta = append(meta, [2]string{"Generated", r.doc.Generated.Format("2 Jan 2006, 15:04")})
	x := pdfMargin
	for _, m := range meta {
		r.font("B", 6.5)
		r.color(pdfFaint)
		f.SetXY(x, y)
		f.CellFormat(0, 3.5, strings.ToUpper(m[0]), "", 0, "L", false, 0, "")
		r.font("", 9.5)
		r.color(pdfInk)
		f.SetXY(x, y+4)
		v := r.text(m[1])
		f.CellFormat(0, 5, v, "", 0, "L", false, 0, "")
		x += math.Max(f.GetStringWidth(v), 22) + 12
	}
	y += 13
	// Two-color rule from the logo.
	f.SetLineWidth(0.8)
	r.draw(pdfAccent)
	f.Line(pdfMargin, y, pdfMargin+r.width-24, y)
	r.draw(pdfSun)
	f.Line(pdfMargin+r.width-24, y, pdfMargin+r.width, y)
	f.SetY(y + 7)
}

// logo draws the sun-and-eye mark, size millimetres square, from the SVG.
func (r *reportPDF) logo(x, y, size float64) {
	paths := logoPaths()
	if len(paths) == 0 {
		return
	}
	const vx, vy, vw = 321.0, 320.0, 1407.0
	k := size / vw
	pt := func(px, py float64) (float64, float64) { return x + (px-vx)*k, y + (py-vy)*k }
	for i, p := range paths {
		if i == 0 {
			r.fill(pdfSun)
		} else {
			r.fill(pdfAccent)
		}
		for _, c := range p {
			switch c.op {
			case 'M':
				r.f.MoveTo(pt(c.v[0], c.v[1]))
			case 'L':
				r.f.LineTo(pt(c.v[0], c.v[1]))
			case 'C':
				x0, y0 := pt(c.v[0], c.v[1])
				x1, y1 := pt(c.v[2], c.v[3])
				x2, y2 := pt(c.v[4], c.v[5])
				r.f.CurveBezierCubicTo(x0, y0, x1, y1, x2, y2)
			}
		}
		r.f.DrawPath("F*")
	}
}

type pathCmd struct {
	op byte
	v  []float64
}

var (
	svgPathAttr = regexp.MustCompile(`\sd="([^"]+)"`)
	svgToken    = regexp.MustCompile(`[MLCmlc]|-?\d*\.?\d+(?:e-?\d+)?`)
	// logoPaths parses the logo's paths once: absolute M, L and C only,
	// which is all the traced logo uses.
	logoPaths = sync.OnceValue(parseLogo)
)

func parseLogo() [][]pathCmd {
	var out [][]pathCmd
	for _, m := range svgPathAttr.FindAllStringSubmatch(logoSVG, -1) {
		var cmds []pathCmd
		var cur *pathCmd
		for _, t := range svgToken.FindAllString(m[1], -1) {
			switch t {
			case "M", "L", "C":
				cmds = append(cmds, pathCmd{op: t[0]})
				cur = &cmds[len(cmds)-1]
			case "m", "l", "c":
				return nil
			default:
				if cur == nil {
					return nil
				}
				n, err := strconv.ParseFloat(t, 64)
				if err != nil {
					return nil
				}
				want := map[byte]int{'M': 2, 'L': 2, 'C': 6}[cur.op]
				// Repeated coordinates continue the same command (M then implicit L).
				if len(cur.v) == want {
					op := cur.op
					if op == 'M' {
						op = 'L'
					}
					cmds = append(cmds, pathCmd{op: op})
					cur = &cmds[len(cmds)-1]
				}
				cur.v = append(cur.v, n)
			}
		}
		out = append(out, cmds)
	}
	return out
}

// ---------- blocks ----------

func toneColor(t string) rgb {
	switch t {
	case "good":
		return pdfGood
	case "bad":
		return pdfBad
	case "warn":
		return pdfWarn
	}
	return pdfMuted
}

func toneWash(t string) rgb {
	switch t {
	case "good":
		return rgb{234, 246, 237}
	case "bad":
		return rgb{252, 236, 236}
	case "warn":
		return rgb{253, 244, 225}
	}
	return pdfTile
}

func (r *reportPDF) verdict(v reportVerdict) {
	f := r.f
	r.font("", 9.5)
	lines := r.split(r.text(v.Text), r.width-20)
	h := 9 + float64(len(lines))*4.6 + 3
	r.need(h + 6)
	y := f.GetY()
	r.fill(toneWash(v.Tone))
	r.draw(toneWash(v.Tone))
	f.RoundedRect(pdfMargin, y, r.width, h, 2, "1234", "F")
	// A round status dot beside the title.
	r.fill(toneColor(v.Tone))
	f.Circle(pdfMargin+6, y+6.4, 1.6, "F")
	r.font("B", 11)
	r.color(toneColor(v.Tone))
	f.SetXY(pdfMargin+10, y+4)
	f.CellFormat(r.width-14, 5, r.text(v.Title), "", 0, "L", false, 0, "")
	r.font("", 9.5)
	r.color(pdfInk)
	f.SetXY(pdfMargin+10, y+9.5)
	f.MultiCell(r.width-20, 4.6, r.text(v.Text), "", "L", false)
	f.SetY(y + h + 6)
}

func (r *reportPDF) heading(title string, keep float64) {
	r.need(12 + keep)
	f := r.f
	y := f.GetY()
	r.font("B", 12)
	r.color(pdfInk)
	f.SetXY(pdfMargin, y)
	f.CellFormat(r.width, 6, r.text(title), "", 0, "L", false, 0, "")
	r.draw(pdfLine)
	f.SetLineWidth(0.25)
	f.Line(pdfMargin, y+7.5, pdfMargin+r.width, y+7.5)
	f.SetY(y + 10)
}

func (r *reportPDF) summary(lines []string) {
	r.heading("Summary", 12)
	f := r.f
	for i, l := range lines {
		if i == 0 {
			r.font("B", 10)
			r.color(pdfInk)
			r.need(6)
			f.SetX(pdfMargin)
			f.MultiCell(r.width, 5, r.text(l), "", "L", false)
			f.SetY(f.GetY() + 1.5)
			continue
		}
		r.font("", 9.5)
		r.color(pdfInk)
		text := r.split(r.text(l), r.width-6)
		r.need(float64(len(text)) * 4.8)
		y := f.GetY()
		r.fill(pdfAccent)
		f.Circle(pdfMargin+1.4, y+2.4, 0.7, "F")
		f.SetXY(pdfMargin+5, y)
		f.MultiCell(r.width-6, 4.8, r.text(l), "", "L", false)
		f.SetY(f.GetY() + 0.8)
	}
	f.SetY(f.GetY() + 5)
}

func (r *reportPDF) stats(stats []emailStat) {
	f := r.f
	perRow := 4
	if len(stats) < perRow {
		perRow = len(stats)
	}
	gap := 3.0
	w := (r.width - gap*float64(perRow-1)) / float64(perRow)
	h := 21.0
	for i := 0; i < len(stats); i += perRow {
		r.need(h + 4)
		y := f.GetY()
		for j, s := range stats[i:min(i+perRow, len(stats))] {
			x := pdfMargin + float64(j)*(w+gap)
			r.fill(pdfTile)
			f.RoundedRect(x, y, w, h, 2, "1234", "F")
			r.font("B", 6.5)
			r.color(pdfMuted)
			f.SetXY(x+4, y+3.5)
			f.CellFormat(w-8, 3.5, r.text(strings.ToUpper(s.Label)), "", 0, "L", false, 0, "")
			r.font("B", 15)
			r.color(pdfInk)
			f.SetXY(x+4, y+8)
			f.CellFormat(w-8, 6.5, r.text(s.Value), "", 0, "L", false, 0, "")
			if s.Change != "" {
				r.font("", 7.5)
				r.color(toneColor(s.Tone))
				f.SetXY(x+4, y+15.2)
				f.CellFormat(w-8, 3.5, r.text(fit(f, r.text(s.Change), w-8)), "", 0, "L", false, 0, "")
			}
		}
		f.SetY(y + h + gap)
	}
	f.SetY(f.GetY() + 4)
}

func (r *reportPDF) chart(c reportChart) {
	const plotH = 38.0
	r.heading(c.Title, plotH+14)
	f := r.f
	if c.Note != "" {
		r.font("", 8.5)
		r.color(pdfMuted)
		f.SetX(pdfMargin)
		f.MultiCell(r.width, 4.2, r.text(c.Note), "", "L", false)
		f.SetY(f.GetY() + 2)
	}
	top := f.GetY() + 4
	base := top + plotH
	maxV := 0.0
	for _, v := range c.Values {
		maxV = math.Max(maxV, v)
	}
	if maxV == 0 {
		maxV = 1
	}
	// Light gridlines at a quarter, half and three quarters, with the scale.
	r.font("", 6.5)
	f.SetLineWidth(0.15)
	r.draw(pdfLine)
	for _, q := range []float64{0.5, 1} {
		gy := base - plotH*q
		f.Line(pdfMargin+12, gy, pdfMargin+r.width, gy)
		r.color(pdfFaint)
		f.SetXY(pdfMargin, gy-1.6)
		f.CellFormat(11, 3.2, compactNum(maxV*q), "", 0, "R", false, 0, "")
	}
	f.SetLineWidth(0.3)
	r.draw(pdfMuted)
	f.Line(pdfMargin+12, base, pdfMargin+r.width, base)
	n := len(c.Values)
	slot := (r.width - 14) / float64(n)
	bw := math.Min(slot*0.62, 16)
	for i, v := range c.Values {
		x := pdfMargin + 14 + float64(i)*slot + (slot-bw)/2
		h := plotH * v / maxV
		r.fill(pdfAccent)
		f.Rect(x, base-h, bw, h, "F")
		if i < len(c.Marks) && c.Marks[i] > 0 {
			mh := math.Max(plotH*c.Marks[i]/maxV, 0.6)
			r.fill(pdfBad)
			f.Rect(x, base-mh, bw, mh, "F")
		}
		r.font("B", 6.5)
		r.color(pdfInk)
		f.SetXY(x-4, base-h-4)
		f.CellFormat(bw+8, 3.2, compactNum(v), "", 0, "C", false, 0, "")
		if i < len(c.Labels) {
			r.font("", 7)
			r.color(pdfMuted)
			f.SetXY(x-6, base+1.5)
			f.CellFormat(bw+12, 3.5, r.text(c.Labels[i]), "", 0, "C", false, 0, "")
		}
	}
	// Legend.
	y := base + 7
	x := pdfMargin + 14
	for _, l := range []struct {
		name string
		c    rgb
	}{{c.ValueName, pdfAccent}, {c.MarkName, pdfBad}} {
		if l.name == "" {
			continue
		}
		r.fill(l.c)
		f.Rect(x, y+0.6, 2.6, 2.6, "F")
		r.font("", 7.5)
		r.color(pdfMuted)
		f.SetXY(x+4, y)
		f.CellFormat(40, 3.8, r.text(l.name), "", 0, "L", false, 0, "")
		x += 6 + f.GetStringWidth(r.text(l.name)) + 8
	}
	f.SetY(y + 10)
}

func (r *reportPDF) section(s emailSection) {
	f := r.f
	r.heading(s.Title, 14)
	if s.Note != "" {
		r.font("", 9)
		r.color(pdfMuted)
		f.SetX(pdfMargin)
		f.MultiCell(r.width, 4.4, r.text(s.Note), "", "L", false)
		f.SetY(f.GetY() + 2.5)
	}
	if len(s.Rows) > 0 {
		r.table(s.Columns, s.Rows)
	}
	f.SetY(f.GetY() + 6)
}

// table lays out the first column flexibly (it wraps) and sizes the others
// to their widest value; the last cell takes the row's tone.
func (r *reportPDF) table(cols []string, rows []emailRow) {
	f := r.f
	n := len(cols)
	if n == 0 && len(rows) > 0 {
		n = len(rows[0].Cells)
	}
	if n == 0 {
		return
	}
	const pad = 2.5
	widths := make([]float64, n)
	rest := 0.0
	for i := 1; i < n; i++ {
		r.font("B", 7)
		w := 0.0
		if i < len(cols) {
			w = f.GetStringWidth(r.text(strings.ToUpper(cols[i])))
		}
		r.font("", 8.5)
		for _, row := range rows {
			if i < len(row.Cells) {
				w = math.Max(w, f.GetStringWidth(r.text(row.Cells[i])))
			}
		}
		widths[i] = math.Min(w+2*pad+1, r.width*0.3)
		rest += widths[i]
	}
	widths[0] = math.Max(r.width-rest, r.width*0.3)
	if over := widths[0] + rest - r.width; over > 0 {
		// Narrow the other columns evenly; their values wrap if they must.
		for i := 1; i < n; i++ {
			widths[i] -= over * widths[i] / rest
		}
	}

	header := func() {
		if len(cols) == 0 {
			return
		}
		y := f.GetY()
		r.fill(pdfHead)
		f.Rect(pdfMargin, y, r.width, 7, "F")
		r.font("B", 7)
		r.color(pdfMuted)
		x := pdfMargin
		for i := 0; i < n; i++ {
			label := ""
			if i < len(cols) {
				label = strings.ToUpper(cols[i])
			}
			align := "R"
			if i == 0 {
				align = "L"
			}
			f.SetXY(x+pad, y)
			f.CellFormat(widths[i]-2*pad, 7, r.text(label), "", 0, align, false, 0, "")
			x += widths[i]
		}
		f.SetY(y + 7)
	}
	r.need(16)
	header()
	const lh = 4.2
	for ri, row := range rows {
		r.font("", 8.5)
		cells := make([][]string, n)
		lines := 1
		for i := 0; i < n; i++ {
			v := ""
			if i < len(row.Cells) {
				v = r.text(row.Cells[i])
			}
			cells[i] = r.split(v, widths[i]-2*pad)
			if len(cells[i]) == 0 {
				cells[i] = []string{""}
			}
			lines = max(lines, len(cells[i]))
		}
		h := float64(lines)*lh + 3.2
		if f.GetY()+h > r.pageBottom() {
			f.AddPage()
			header()
		}
		y := f.GetY()
		if ri%2 == 1 {
			r.fill(pdfZebra)
			f.Rect(pdfMargin, y, r.width, h, "F")
		}
		x := pdfMargin
		for i := 0; i < n; i++ {
			align := "R"
			if i == 0 {
				align = "L"
			}
			last := i == n-1 && row.Tone != ""
			if last {
				r.font("B", 8.5)
				r.color(toneColor(row.Tone))
			} else {
				r.font("", 8.5)
				r.color(pdfInk)
			}
			for li, l := range cells[i] {
				f.SetXY(x+pad, y+1.6+float64(li)*lh)
				f.CellFormat(widths[i]-2*pad, lh, l, "", 0, align, false, 0, "")
			}
			x += widths[i]
		}
		r.draw(pdfLine)
		f.SetLineWidth(0.15)
		f.Line(pdfMargin, y+h, pdfMargin+r.width, y+h)
		f.SetY(y + h)
	}
}

func (r *reportPDF) footnote(text string) {
	f := r.f
	r.font("", 7.5)
	lines := r.split(r.text(text), r.width)
	r.need(float64(len(lines))*3.8 + 6)
	y := f.GetY() + 2
	r.draw(pdfLine)
	f.SetLineWidth(0.2)
	f.Line(pdfMargin, y, pdfMargin+r.width, y)
	r.color(pdfFaint)
	f.SetXY(pdfMargin, y+2.5)
	f.MultiCell(r.width, 3.8, r.text(text), "", "L", false)
}

// split wraps already-translated text to lines at most w wide in the
// current font, at spaces where it can and mid-word where it must (long
// routes and paths). fpdf's SplitText expects UTF-8, which this is not.
func (r *reportPDF) split(s string, w float64) []string {
	var lines []string
	for _, para := range strings.Split(s, "\n") {
		line := ""
		for _, word := range strings.Fields(para) {
			try := word
			if line != "" {
				try = line + " " + word
			}
			if r.f.GetStringWidth(try) <= w {
				line = try
				continue
			}
			if line != "" {
				lines = append(lines, line)
			}
			for r.f.GetStringWidth(word) > w && len(word) > 1 {
				cut := len(word) - 1
				for cut > 1 && r.f.GetStringWidth(word[:cut]) > w {
					cut--
				}
				lines = append(lines, word[:cut])
				word = word[cut:]
			}
			line = word
		}
		lines = append(lines, line)
	}
	return lines
}

// fit shortens s with an ellipsis so it is at most w wide in the current font.
func fit(f *fpdf.Fpdf, s string, w float64) string {
	if f.GetStringWidth(s) <= w {
		return s
	}
	for len(s) > 1 && f.GetStringWidth(s+"...") > w {
		s = s[:len(s)-1]
	}
	return s + "..."
}

// compactNum is 950, 12.4k or 3.1M.
func compactNum(v float64) string {
	a := math.Abs(v)
	switch {
	case a >= 1e6:
		return strconv.FormatFloat(v/1e6, 'f', 1, 64) + "M"
	case a >= 1e4:
		return strconv.FormatFloat(v/1e3, 'f', 0, 64) + "k"
	case a >= 1e3:
		return strconv.FormatFloat(v/1e3, 'f', 1, 64) + "k"
	}
	return strconv.FormatFloat(math.Round(v), 'f', 0, 64)
}
