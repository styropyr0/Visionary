CREATE TABLE IF NOT EXISTS system_metrics (
    id                 BIGINT       NOT NULL AUTO_INCREMENT PRIMARY KEY,
    created_at         VARCHAR(32)  NOT NULL,
    instance           VARCHAR(128) NOT NULL,
    interval_s         DOUBLE       NOT NULL,
    host_cpu_percent   DOUBLE,
    load_1             DOUBLE,
    load_5             DOUBLE,
    load_15            DOUBLE,
    host_mem_used_mb   DOUBLE,
    host_mem_total_mb  DOUBLE,
    host_mem_percent   DOUBLE,
    disk_used_percent  DOUBLE,
    disk_free_gb       DOUBLE,
    net_rx_kbps        DOUBLE,
    net_tx_kbps        DOUBLE,
    proc_cpu_percent   DOUBLE,
    proc_rss_mb        DOUBLE,
    proc_threads       INT,
    proc_open_fds      INT,
    goroutines         INT,
    heap_alloc_mb      DOUBLE,
    heap_inuse_mb      DOUBLE,
    heap_objects       BIGINT,
    gc_count           INT,
    gc_pause_ms        DOUBLE,
    gc_cpu_percent     DOUBLE,
    db_total_conns     INT,
    db_idle_conns      INT,
    db_acquired_conns  INT,
    db_max_conns       INT,
    db_acquires        BIGINT,
    db_empty_acquires  BIGINT,
    db_acquire_wait_ms DOUBLE,
    http_requests      BIGINT,
    http_errors        BIGINT,
    http_rps           DOUBLE,
    http_in_flight     INT,
    uptime_s           BIGINT,
    cpu_count          BIGINT,
    cpu_user_percent   DOUBLE,
    cpu_system_percent DOUBLE,
    cpu_iowait_percent DOUBLE,
    cpu_steal_percent  DOUBLE,
    host_mem_available_mb DOUBLE,
    host_mem_cached_mb DOUBLE,
    swap_used_mb       DOUBLE,
    swap_total_mb      DOUBLE,
    disk_total_gb      DOUBLE,
    disk_inodes_percent DOUBLE,
    disk_read_kbps     DOUBLE,
    disk_write_kbps    DOUBLE,
    disk_read_iops     DOUBLE,
    disk_write_iops    DOUBLE,
    disk_busy_percent  DOUBLE,
    disk_await_ms      DOUBLE,
    net_rx_pps         DOUBLE,
    net_tx_pps         DOUBLE,
    net_errors         BIGINT,
    net_drops          BIGINT,
    tcp_established    BIGINT,
    tcp_retrans        BIGINT,
    host_procs         BIGINT,
    procs_running      BIGINT,
    procs_blocked      BIGINT,
    ctx_switches_ps    DOUBLE,
    proc_read_kbps     DOUBLE,
    proc_write_kbps    DOUBLE,
    proc_max_fds       BIGINT,
    service            VARCHAR(255),
    version            VARCHAR(255)
) CHARACTER SET utf8mb4;
CREATE INDEX idx_system_metrics_created_at ON system_metrics (created_at);
CREATE INDEX idx_system_metrics_instance_created ON system_metrics (instance, created_at);
