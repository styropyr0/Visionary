CREATE TABLE IF NOT EXISTS system_metrics (
    id                 INTEGER PRIMARY KEY AUTOINCREMENT,
    created_at         TEXT    NOT NULL,
    instance           TEXT    NOT NULL,
    interval_s         REAL    NOT NULL,
    host_cpu_percent   REAL,
    load_1             REAL,
    load_5             REAL,
    load_15            REAL,
    host_mem_used_mb   REAL,
    host_mem_total_mb  REAL,
    host_mem_percent   REAL,
    disk_used_percent  REAL,
    disk_free_gb       REAL,
    net_rx_kbps        REAL,
    net_tx_kbps        REAL,
    proc_cpu_percent   REAL,
    proc_rss_mb        REAL,
    proc_threads       INTEGER,
    proc_open_fds      INTEGER,
    goroutines         INTEGER,
    heap_alloc_mb      REAL,
    heap_inuse_mb      REAL,
    heap_objects       INTEGER,
    gc_count           INTEGER,
    gc_pause_ms        REAL,
    gc_cpu_percent     REAL,
    db_total_conns     INTEGER,
    db_idle_conns      INTEGER,
    db_acquired_conns  INTEGER,
    db_max_conns       INTEGER,
    db_acquires        INTEGER,
    db_empty_acquires  INTEGER,
    db_acquire_wait_ms REAL,
    http_requests      INTEGER,
    http_errors        INTEGER,
    http_rps           REAL,
    http_in_flight     INTEGER,
    uptime_s           INTEGER
);
CREATE INDEX IF NOT EXISTS idx_system_metrics_created_at ON system_metrics (created_at);
CREATE INDEX IF NOT EXISTS idx_system_metrics_instance_created ON system_metrics (instance, created_at);
