CREATE TABLE IF NOT EXISTS system_metrics (
    id                 BIGSERIAL PRIMARY KEY,
    created_at         TEXT             NOT NULL,
    instance           TEXT             NOT NULL,
    interval_s         DOUBLE PRECISION NOT NULL,
    host_cpu_percent   DOUBLE PRECISION,
    load_1             DOUBLE PRECISION,
    load_5             DOUBLE PRECISION,
    load_15            DOUBLE PRECISION,
    host_mem_used_mb   DOUBLE PRECISION,
    host_mem_total_mb  DOUBLE PRECISION,
    host_mem_percent   DOUBLE PRECISION,
    disk_used_percent  DOUBLE PRECISION,
    disk_free_gb       DOUBLE PRECISION,
    net_rx_kbps        DOUBLE PRECISION,
    net_tx_kbps        DOUBLE PRECISION,
    proc_cpu_percent   DOUBLE PRECISION,
    proc_rss_mb        DOUBLE PRECISION,
    proc_threads       INTEGER,
    proc_open_fds      INTEGER,
    goroutines         INTEGER,
    heap_alloc_mb      DOUBLE PRECISION,
    heap_inuse_mb      DOUBLE PRECISION,
    heap_objects       BIGINT,
    gc_count           INTEGER,
    gc_pause_ms        DOUBLE PRECISION,
    gc_cpu_percent     DOUBLE PRECISION,
    db_total_conns     INTEGER,
    db_idle_conns      INTEGER,
    db_acquired_conns  INTEGER,
    db_max_conns       INTEGER,
    db_acquires        BIGINT,
    db_empty_acquires  BIGINT,
    db_acquire_wait_ms DOUBLE PRECISION,
    http_requests      BIGINT,
    http_errors        BIGINT,
    http_rps           DOUBLE PRECISION,
    http_in_flight     INTEGER,
    uptime_s           BIGINT
);
CREATE INDEX IF NOT EXISTS idx_system_metrics_created_at ON system_metrics (created_at);
CREATE INDEX IF NOT EXISTS idx_system_metrics_instance_created ON system_metrics (instance, created_at);
