CREATE TABLE IF NOT EXISTS system_metrics (
    id                 BIGINT       NOT NULL AUTO_INCREMENT PRIMARY KEY,
    created_at         VARCHAR(32)  NOT NULL,
    instance           VARCHAR(128) NOT NULL,
    interval_s         DOUBLE       NOT NULL,
    host_cpu_percent   DOUBLE,
    load_1             DOUBLE,
    load_5             DOUBLE,
    load_15            DOUBLE,
    host_mem_used_mb   DOUBLE,
    host_mem_total_mb  DOUBLE,
    host_mem_percent   DOUBLE,
    disk_used_percent  DOUBLE,
    disk_free_gb       DOUBLE,
    net_rx_kbps        DOUBLE,
    net_tx_kbps        DOUBLE,
    proc_cpu_percent   DOUBLE,
    proc_rss_mb        DOUBLE,
    proc_threads       INT,
    proc_open_fds      INT,
    goroutines         INT,
    heap_alloc_mb      DOUBLE,
    heap_inuse_mb      DOUBLE,
    heap_objects       BIGINT,
    gc_count           INT,
    gc_pause_ms        DOUBLE,
    gc_cpu_percent     DOUBLE,
    db_total_conns     INT,
    db_idle_conns      INT,
    db_acquired_conns  INT,
    db_max_conns       INT,
    db_acquires        BIGINT,
    db_empty_acquires  BIGINT,
    db_acquire_wait_ms DOUBLE,
    http_requests      BIGINT,
    http_errors        BIGINT,
    http_rps           DOUBLE,
    http_in_flight     INT,
    uptime_s           BIGINT
) CHARACTER SET utf8mb4;
CREATE INDEX idx_system_metrics_created_at ON system_metrics (created_at);
CREATE INDEX idx_system_metrics_instance_created ON system_metrics (instance, created_at);
